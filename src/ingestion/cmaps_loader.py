"""
CMaps (NASA Turbofan Jet Engine) Data Loader and Preprocessor.
Handles:
- Primary data input path: /Users/shifashameer/Downloads/CMaps
- Parsing space-separated text files (train_FD00x.txt, test_FD00x.txt, RUL_FD00x.txt)
- Assigning headers, column names (unit_number, time_cycles, settings, sensors)
- Supplying missing index columns for RUL files (unit_number: 1..N)
- Safely ignoring non-data files (readme.txt, Damage Propagation Modeling.pdf, etc.)
- Telemetry preprocessing, RUL computation, and object partitioning for data lifecycle optimization.
"""

import os
import re
import numpy as np
import pandas as pd
from pathlib import Path
from typing import Dict, List, Optional, Tuple

# Primary path directly pointing to teammate's local Mac directory
DEFAULT_CMAPS_DIR = "/Users/shifashameer/Downloads/CMaps"

# Fallback paths for local development / testing
FALLBACK_DIRS = [
    os.path.join("data", "raw", "CMaps"),
    os.path.join("data", "raw"),
    r"C:\research\CMaps",
]

# Standard NASA Turbofan 26-column layout
CMAPS_COLUMNS = [
    "unit_number",
    "time_cycles",
    "op_setting_1",
    "op_setting_2",
    "op_setting_3",
] + [f"sensor_{i}" for i in range(1, 22)]

# File patterns
DATA_FILE_PATTERN = re.compile(r"^(train|test|RUL)_(FD\d{3})\.txt$", re.IGNORECASE)
DOC_FILE_PATTERN = re.compile(r"(readme.*|damage\s*propaga.*|.*\.pdf$)", re.IGNORECASE)


def resolve_cmaps_dir(custom_path: Optional[str] = None) -> str:
    """
    Resolve the CMaps directory path.
    Prioritizes:
    1. custom_path if provided and exists
    2. Primary Mac path: /Users/shifashameer/Downloads/CMaps
    3. CMAPS_DATA_DIR environment variable
    4. Local project fallback directories
    """
    if custom_path and os.path.isdir(custom_path):
        return custom_path

    # Primary target path on Shifa's Mac
    if os.path.isdir(DEFAULT_CMAPS_DIR):
        return DEFAULT_CMAPS_DIR

    # Environment variable override
    env_dir = os.environ.get("CMAPS_DATA_DIR")
    if env_dir and os.path.isdir(env_dir):
        return env_dir

    # Check fallbacks for local testing
    for fb in FALLBACK_DIRS:
        if os.path.isdir(fb):
            return fb

    # If nothing exists yet, return default Mac path
    return DEFAULT_CMAPS_DIR


def is_valid_cmaps_data_file(filename: str) -> bool:
    """Return True if filename is a valid CMaps data file (train/test/RUL)."""
    basename = os.path.basename(filename)
    return bool(DATA_FILE_PATTERN.match(basename))


def is_ignored_cmaps_file(filename: str) -> bool:
    """Return True if the file is documentation or metadata that should be ignored."""
    basename = os.path.basename(filename)
    if not is_valid_cmaps_data_file(basename):
        return True
    return bool(DOC_FILE_PATTERN.match(basename))


def parse_cmaps_file(filepath: str) -> pd.DataFrame:
    """
    Parse a space-separated CMaps train or test text file.
    - Handles variable whitespace and trailing spaces
    - Drops any trailing empty / all-NaN columns caused by trailing spaces
    - Assigns standard 26 column names
    - Enforces proper integer and float types
    """
    if not os.path.isfile(filepath):
        raise FileNotFoundError(f"CMaps file not found: {filepath}")

    # Read space-separated values without header
    df = pd.read_csv(filepath, sep=r"\s+", header=None, engine="python")

    # Drop columns that are completely NaN (often generated by trailing whitespace)
    df = df.dropna(axis=1, how="all")

    # Ensure exactly 26 columns are present
    if df.shape[1] > len(CMAPS_COLUMNS):
        df = df.iloc[:, :len(CMAPS_COLUMNS)]
    elif df.shape[1] < len(CMAPS_COLUMNS):
        raise ValueError(
            f"Expected 26 columns in {filepath}, but parsed {df.shape[1]} columns."
        )

    df.columns = CMAPS_COLUMNS
    df["unit_number"] = df["unit_number"].astype(int)
    df["time_cycles"] = df["time_cycles"].astype(int)

    for col in ["op_setting_1", "op_setting_2", "op_setting_3"] + [f"sensor_{i}" for i in range(1, 22)]:
        df[col] = pd.to_numeric(df[col], errors="coerce").astype(float)

    return df


def parse_rul_file(filepath: str) -> pd.DataFrame:
    """
    Parse a space-separated CMaps Remaining Useful Life (RUL) file.
    - Handles variable whitespace / trailing spaces
    - Drops any trailing empty / all-NaN columns
    - Assigns 'RUL' column name
    - Supplies the MISSING INDEX COLUMN 'unit_number' (1-indexed, 1..N)
    """
    if not os.path.isfile(filepath):
        raise FileNotFoundError(f"CMaps RUL file not found: {filepath}")

    df = pd.read_csv(filepath, sep=r"\s+", header=None, engine="python")
    df = df.dropna(axis=1, how="all")

    if df.shape[1] > 1:
        df = df.iloc[:, :1]

    df.columns = ["RUL"]
    df["RUL"] = pd.to_numeric(df["RUL"], errors="coerce").astype(int)

    # Supply missing index column: row 0 -> unit 1, row 1 -> unit 2, etc.
    df.insert(0, "unit_number", np.arange(1, len(df) + 1, dtype=int))

    return df


def load_cmaps_subset(
    data_dir: str,
    subset: str = "FD001",
) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    """
    Load train, test, and RUL files for a given subset (e.g. FD001).
    Calculates ground-truth Remaining Useful Life (RUL) across both train and test.
    """
    train_path = os.path.join(data_dir, f"train_{subset}.txt")
    test_path = os.path.join(data_dir, f"test_{subset}.txt")
    rul_path = os.path.join(data_dir, f"RUL_{subset}.txt")

    train_df = parse_cmaps_file(train_path)
    test_df = parse_cmaps_file(test_path)
    rul_df = parse_rul_file(rul_path)

    # Compute RUL for training data: run-to-failure means RUL = max_cycle - current_cycle
    max_train_cycles = train_df.groupby("unit_number")["time_cycles"].transform("max")
    train_df["RUL"] = max_train_cycles - train_df["time_cycles"]

    # Compute RUL for test data: last recorded cycle has RUL given in rul_df
    last_test_cycles = test_df.groupby("unit_number")["time_cycles"].transform("max")
    unit_rul_dict = rul_df.set_index("unit_number")["RUL"].to_dict()
    rul_at_end = test_df["unit_number"].map(unit_rul_dict)
    test_df["RUL"] = rul_at_end + (last_test_cycles - test_df["time_cycles"])

    return train_df, test_df, rul_df


def discover_cmaps_files(data_dir: str) -> Dict[str, Dict[str, str]]:
    """
    Discover all valid CMaps files in the specified directory, organized by subset.
    Safely ignores documentation files like readme.txt and Damage Propagation Modeling.pdf.

    Returns:
        Dict mapping subset (e.g. 'FD001') to a dict of {'train': path, 'test': path, 'rul': path}
    """
    if not os.path.isdir(data_dir):
        return {}

    discovered: Dict[str, Dict[str, str]] = {}
    ignored_files = []

    for entry in sorted(os.listdir(data_dir)):
        full_path = os.path.join(data_dir, entry)
        if not os.path.isfile(full_path):
            continue

        match = DATA_FILE_PATTERN.match(entry)
        if match:
            kind, subset = match.group(1).lower(), match.group(2).upper()
            if subset not in discovered:
                discovered[subset] = {}
            discovered[subset][kind] = full_path
        else:
            # Documentation, pdf, or non-data file -> safely ignore
            ignored_files.append(entry)

    if ignored_files:
        print(f"CMaps Loader: Safely ignored {len(ignored_files)} non-data file(s): {ignored_files}", flush=True)

    return discovered


def engineer_telemetry_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Feature engineering on parsed CMaps sensor telemetry:
    - Normalizes operational settings
    - Computes rolling statistics (mean, std) for key sensors
    - Computes cycle progress ratio and sensor variance
    """
    df = df.copy()

    # Active sensors (sensors that change over time; constant sensors like 1, 5, 10 in FD001 have ~0 std)
    active_sensors = []
    for i in range(1, 22):
        col = f"sensor_{i}"
        if df[col].std() > 1e-4:
            active_sensors.append(col)

    # Rolling statistics per unit
    for col in active_sensors[:6]:  # top active sensors for lightweight fast processing
        df[f"{col}_rolling_mean_5"] = (
            df.groupby("unit_number")[col]
            .transform(lambda x: x.rolling(5, min_periods=1).mean())
        )
        df[f"{col}_rolling_std_5"] = (
            df.groupby("unit_number")[col]
            .transform(lambda x: x.rolling(5, min_periods=1).std().fillna(0.0))
        )

    # Engine cycle progression ratio
    max_c = df.groupby("unit_number")["time_cycles"].transform("max")
    df["cycle_progress"] = df["time_cycles"] / np.maximum(1, max_c)

    return df


def generate_sample_cmaps_dataset(target_dir: str, num_units: int = 15) -> None:
    """
    Generates authentic, space-separated NASA Turbofan Jet Engine (CMaps) data files.
    Matches the exact 26-column space-delimited format, RUL single-column format,
    plus readme.txt and Damage Propagation Modeling.pdf documentation.
    Used for local testing when primary Mac directory is not mounted.
    """
    os.makedirs(target_dir, exist_ok=True)
    rng = np.random.default_rng(42)

    subsets = ["FD001", "FD002", "FD003", "FD004"]

    for subset in subsets:
        # Base sensor baselines for standard turbofan sea-level operating mode
        base_s = np.array([
            518.67, 642.50, 1589.70, 1405.20, 14.62,
            21.61, 554.10, 2388.08, 9050.20, 1.30,
            47.45, 521.60, 2388.06, 8135.20, 8.42,
            0.03, 392.00, 2388.00, 100.00, 38.90, 23.35,
        ])

        # 1. Generate train_FD00x.txt
        train_rows = []
        for unit in range(1, num_units + 1):
            max_cycles = rng.integers(120, 280)
            for c in range(1, max_cycles + 1):
                deg = (c / max_cycles) ** 1.8  # degradation progression
                # settings
                s1 = float(rng.normal(-0.0002, 0.001))
                s2 = float(rng.normal(0.0001, 0.0002))
                s3 = 100.0
                # sensors with realistic drift
                sensors = base_s.copy()
                sensors[1] += deg * 5.0 + rng.normal(0, 0.2)   # sensor 2 increases
                sensors[2] += deg * 20.0 + rng.normal(0, 0.8)  # sensor 3 increases
                sensors[3] += deg * 15.0 + rng.normal(0, 0.5)  # sensor 4 increases
                sensors[6] -= deg * 2.5 + rng.normal(0, 0.1)   # sensor 7 decreases
                sensors[8] -= deg * 10.0 + rng.normal(0, 0.4)  # sensor 9 decreases
                sensors[10] -= deg * 0.5 + rng.normal(0, 0.05) # sensor 11 decreases
                sensors[13] += deg * 12.0 + rng.normal(0, 0.3) # sensor 14 increases
                # add noise to other active sensors
                for si in [14, 16, 19, 20]:
                    sensors[si] += deg * rng.uniform(-0.5, 0.5) + rng.normal(0, 0.05)

                row_vals = [f"{unit}", f"{c}", f"{s1:.4f}", f"{s2:.4f}", f"{s3:.1f}"]
                row_vals.extend([f"{sv:.2f}" for sv in sensors])
                train_rows.append(" ".join(row_vals) + "  \n")  # include trailing space to test robust parsing

        train_path = os.path.join(target_dir, f"train_{subset}.txt")
        with open(train_path, "w", encoding="utf-8") as f:
            f.writelines(train_rows)

        # 2. Generate test_FD00x.txt and RUL_FD00x.txt
        test_rows = []
        rul_rows = []
        for unit in range(1, num_units + 1):
            total_life = rng.integers(150, 280)
            remaining_rul = rng.integers(20, 110)
            cut_cycle = total_life - remaining_rul
            rul_rows.append(f"{remaining_rul} \n")

            for c in range(1, cut_cycle + 1):
                deg = (c / total_life) ** 1.8
                s1 = float(rng.normal(-0.0002, 0.001))
                s2 = float(rng.normal(0.0001, 0.0002))
                s3 = 100.0
                sensors = base_s.copy()
                sensors[1] += deg * 5.0 + rng.normal(0, 0.2)
                sensors[2] += deg * 20.0 + rng.normal(0, 0.8)
                sensors[3] += deg * 15.0 + rng.normal(0, 0.5)
                sensors[6] -= deg * 2.5 + rng.normal(0, 0.1)
                sensors[8] -= deg * 10.0 + rng.normal(0, 0.4)
                sensors[10] -= deg * 0.5 + rng.normal(0, 0.05)
                sensors[13] += deg * 12.0 + rng.normal(0, 0.3)
                for si in [14, 16, 19, 20]:
                    sensors[si] += deg * rng.uniform(-0.5, 0.5) + rng.normal(0, 0.05)

                row_vals = [f"{unit}", f"{c}", f"{s1:.4f}", f"{s2:.4f}", f"{s3:.1f}"]
                row_vals.extend([f"{sv:.2f}" for sv in sensors])
                test_rows.append(" ".join(row_vals) + "  \n")

        test_path = os.path.join(target_dir, f"test_{subset}.txt")
        with open(test_path, "w", encoding="utf-8") as f:
            f.writelines(test_rows)

        rul_path = os.path.join(target_dir, f"RUL_{subset}.txt")
        with open(rul_path, "w", encoding="utf-8") as f:
            f.writelines(rul_rows)

    # 3. Add documentation files to verify that loader safely ignores them
    readme_path = os.path.join(target_dir, "readme.txt")
    with open(readme_path, "w", encoding="utf-8") as f:
        f.write(
            "Turbofan Engine Degradation Simulation Data Set (C-MAPSS)\n"
            "Reference: A. Saxena, K. Goebel, D. Simon, and N. Eklund (2008)\n"
            "Data Sets: FD001, FD002, FD003, FD004\n"
            "Format: space-delimited text without headers.\n"
        )

    pdf_path = os.path.join(target_dir, "Damage Propagation Modeling.pdf")
    with open(pdf_path, "wb") as f:
        f.write(b"%PDF-1.4 NASA Damage Propagation Modeling Documentation Mock")

    print(f"Generated sample CMaps dataset at {target_dir} ({len(subsets)} subsets).", flush=True)
